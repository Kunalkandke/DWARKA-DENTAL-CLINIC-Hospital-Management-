const { paymentDb, invoiceDb, patientDb, clinicDb } = require('../db')
const { isValidUUID } = require('../utils/isValidUUID')
const ApiError = require('../utils/ApiError')

/** Fetch all non-deleted payments with filter/sort/pagination */
async function getAllPayments(query = {}) {
  const {
    status,
    patientId: qPatient,
    doctorId,
    dateFrom,
    dateTo,
    sortBy = 'paidAt',
    sortOrder = 'desc',
    page = 1,
    limit = 50,
  } = query

  const filter = {
    sortBy,
    sortOrder,
    page,
    limit,
  }
  if (qPatient && isValidUUID(qPatient)) filter.patient_id = qPatient
  if (status) filter.status = status
  if (dateFrom) filter.date_from = dateFrom
  if (dateTo) filter.date_to = dateTo

  const { data, total } = await paymentDb.findAll(filter)

  const pageNum = Math.max(1, parseInt(page))
  const pageLimit = Math.min(100, Math.max(1, parseInt(limit)))

  return {
    data: data.map((p) => toFrontendShape(p, p.patient ? p.patient.name : '')),
    pagination: { page: pageNum, limit: pageLimit, total, totalPages: Math.ceil(total / pageLimit) },
  }
}

/**
 * Get payments for a specific patient with outstanding calculation.
 */
async function getPaymentsByPatient(patientId) {
  const payments = await paymentDb.findByPatient(patientId)

  const totalPaid = payments.reduce((sum, p) => sum + (p.amount || 0), 0) / 100

  return {
    payments: payments.map((p) => toFrontendShape(p)),
    totalPaid,
  }
}

/** Record a new payment */
async function addPayment(body, requestingUser) {
  const clinic = await clinicDb.getDefaultClinic()
  const { patientId, appointmentId, amount, mode, notes, date } = body

  const patient = await patientDb.findById(patientId)
  if (!patient || patient.is_deleted) throw ApiError.notFound('Patient not found.')

  const amountPaise = Math.round(parseFloat(amount) * 100)

  // invoice_number is auto-generated by sequence — do NOT pass it
  const { invoice } = await invoiceDb.createWithItems(
    {
      clinic_id: clinic.id,
      patient_id: patient.id,
      ...(appointmentId ? { appointment_id: appointmentId } : {}),
      subtotal: amountPaise,
      discount: 0,
      tax: 0,
      total: amountPaise,
      amount_paid: amountPaise,
      balance_due: 0,
      status: 'paid',
      issued_at: new Date().toISOString(),
      due_at: new Date().toISOString(),
    },
    [
      {
        description: notes || 'Payment',
        quantity: 1,
        unit_price: amountPaise,
        discount: 0,
        amount: amountPaise,
      },
    ]
  )

  // receipt_number is auto-generated by sequence — do NOT pass it
  const payment = await paymentDb.create({
    clinic_id: clinic.id,
    invoice_id: invoice.id,
    patient_id: patient.id,
    amount: amountPaise,
    method: mode.toLowerCase(),
    status: 'paid',
    notes: notes || '',
    paid_at: date ? new Date(date).toISOString() : new Date().toISOString(),
    recorded_by_id: requestingUser ? requestingUser.id : clinic.id,
  })

  return toFrontendShape(payment, patient.name)
}

/** Soft-delete a payment (Admin only) */
async function softDeletePayment(id) {
  await paymentDb.softDelete(id)
}

/** Revenue summary */
async function getRevenueSummary() {
  const clinic = await clinicDb.getDefaultClinic()
  const result = await paymentDb.getRevenueSummary(clinic.id)
  const totalPaise = result.reduce((sum, r) => sum + r.value, 0)
  return {
    totalPaid: totalPaise / 100,
    byMode: result.map((r) => ({ mode: r.method, value: r.value / 100 })),
  }
}

function toFrontendShape(p, patientName = '') {
  const name = patientName || (p.patient && typeof p.patient === 'object' ? p.patient.name : '')
  return {
    id: p.id,
    patientId: p.patient_id || null,
    patientName: name,
    appointmentId: p.appointment_id || null,
    amount: (p.amount || 0) / 100,
    mode: p.method,
    notes: p.notes || '',
    date: p.paid_at ? new Date(p.paid_at).toISOString().split('T')[0] : null,
    status: p.status,
    receiptNumber: p.receipt_number,
    isDeleted: p.is_deleted,
  }
}

module.exports = { getAllPayments, getPaymentsByPatient, addPayment, softDeletePayment, getRevenueSummary }
