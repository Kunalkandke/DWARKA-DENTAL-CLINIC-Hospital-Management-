@app.get("/health")
def health() -> dict:
    """Health-check – always public, no API key required."""
    return {
        "status": "ok",
        "model_loaded": _model_loaded,
        "classes": CLASS_NAMES,
        **({"error": _model_load_error} if not _model_loaded else {}),
    }


@app.post("/predict")
async def predict(
    file: UploadFile = File(...),
    x_api_key: str | None = Header(default=None),
) -> dict:
    """
    Primary prediction endpoint.
    Accepts a multipart/form-data field named 'file' (JPG or PNG, ≤ 10 MB).
    """
    _check_api_key(x_api_key)

    if not _model_loaded:
        raise HTTPException(
            status_code=503,
            detail=f"Model is not loaded. Startup error: {_model_load_error or 'unknown'}",
        )

    data = await file.read()
    img = _validate_image_bytes(data, file.filename or "upload")

    try:
        response = await run_in_threadpool(_run_prediction, img)
    except RuntimeError as exc:
        raise HTTPException(status_code=500, detail=str(exc)) from exc

    return response


@app.post("/analyze")
async def analyze(
    file: UploadFile = File(...),
    x_api_key: str | None = Header(default=None),
) -> dict:
    """
    Legacy alias for /predict – delegates to the same logic.
    Kept for backward compatibility with existing callers.
    """
    return await predict(file=file, x_api_key=x_api_key)
