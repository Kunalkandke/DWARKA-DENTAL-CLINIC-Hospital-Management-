def _check_api_key(x_api_key: str | None) -> None:
    """Raise 401 if the service is protected and the key is wrong/missing."""
    if ML_API_KEY is not None:
        if x_api_key != ML_API_KEY:
            raise HTTPException(status_code=401, detail="Invalid or missing API key.")


def _validate_image_bytes(data: bytes, filename: str) -> np.ndarray:
    """
    Validate size, extension/mime, decodability, and colour check.
    Returns the decoded BGR image array on success.
    Raises HTTPException(400) on any validation failure.
    """
    # 1. Size
    if len(data) > MAX_FILE_SIZE:
        raise HTTPException(
            status_code=400,
            detail=f"File too large. Maximum allowed size is 10 MB.",
        )

    # 2. Extension
    ext = Path(filename).suffix.lower()
    if ext not in ALLOWED_EXTENSIONS:
        raise HTTPException(
            status_code=400,
            detail=f"Unsupported file type '{ext}'. Only JPG and PNG images are accepted.",
        )

    # 3. Decode
    arr = np.frombuffer(data, np.uint8)
    img: np.ndarray | None = cv2.imdecode(arr, cv2.IMREAD_COLOR)
    if img is None:
        raise HTTPException(
            status_code=400,
            detail="Image could not be decoded. Please upload a valid JPG or PNG file.",
        )

    # 4. Colour check – dental X-rays are near-grayscale
    b_ch, g_ch, r_ch = img[:, :, 0].astype(float), img[:, :, 1].astype(float), img[:, :, 2].astype(float)
    mean_colour_diff = float(
        np.mean(np.abs(r_ch - g_ch)) / 2
        + np.mean(np.abs(r_ch - b_ch)) / 2
        + np.mean(np.abs(g_ch - b_ch)) / 2
    )
    if mean_colour_diff > COLOUR_THRESHOLD:
        raise HTTPException(
            status_code=400,
            detail=(
                "This does not look like a dental X-ray (grayscale expected). "
                f"Detected mean channel difference: {mean_colour_diff:.1f} (threshold: {COLOUR_THRESHOLD})."
            ),
        )

    return img


def _run_prediction(img: np.ndarray) -> dict:
    """
    Run YOLO inference synchronously (intended for run_in_threadpool).
    Returns the fully-assembled response dict.
    Raises RuntimeError on inference failure.
    """
    if not _model_loaded or _model is None:
        raise RuntimeError(
            f"Model is not loaded. Startup error: {_model_load_error or 'unknown'}"
        )

    try:
        results = _model.predict(img, conf=CONF, imgsz=IMGSZ, augment=True, verbose=False)
    except Exception as exc:
        raise RuntimeError(f"Model inference failed: {exc}") from exc

    result = results[0]

    # -- Annotated image --
    annotated_bgr: np.ndarray = result.plot()
    ok, buf = cv2.imencode(".png", annotated_bgr)
    if not ok:
        raise RuntimeError("Failed to encode annotated image as PNG.")
    annotated_b64 = "data:image/png;base64," + base64.b64encode(buf.tobytes()).decode()

    height, width = img.shape[:2]

    # -- Findings --
    findings: list[dict] = []
    for box in result.boxes:
        label = _model.names[int(box.cls[0])]
        conf_val = round(float(box.conf[0]), 4)
        x1, y1, x2, y2 = [round(v, 1) for v in box.xyxy[0].tolist()]
        findings.append(
            {
                "label": label,
                "confidence": conf_val,
                "box": [x1, y1, x2, y2],
                "suggestion": SUGGESTIONS.get(label, ""),
            }
        )

    # Sort by confidence descending
    findings.sort(key=lambda f: f["confidence"], reverse=True)

    # -- Top-level result field --
    has_cavity = any(f["label"] == "Cavity" for f in findings)
    has_any = len(findings) > 0

    if has_cavity:
        result_label = "cavity"
    elif has_any:
        result_label = "findings_detected"
    else:
        result_label = "normal"

    # -- Confidence (highest single detection, or 0) --
    top_confidence: float = findings[0]["confidence"] if findings else 0.0

    # -- Count --
    count = len(findings)

    # -- Summary sentence --
    if not findings:
        summary = "No findings above the confidence threshold."
    else:
        from collections import Counter
        class_counts = Counter(f["label"] for f in findings)
        parts = [f"{v} {k}{'s' if v > 1 else ''}" for k, v in class_counts.items()]
        if len(parts) == 1:
            summary = f"Detected {parts[0]}."
        else:
            summary = "Detected " + ", ".join(parts[:-1]) + f", and {parts[-1]}."

    # -- Unique suggestions (preserving order of first occurrence) --
    seen: set[str] = set()
    suggestions: list[str] = []
    for f in findings:
        s = f["suggestion"]
        if s and s not in seen:
            seen.add(s)
            suggestions.append(s)

    return {
        "modelVersion": MODEL_VERSION,
        "result": result_label,
        "confidence": round(top_confidence, 4),
        "count": count,
        "summary": summary,
        "suggestions": suggestions,
        "findings": findings,
        "imageWidth": width,
        "imageHeight": height,
        # Only include the heavy base64 field when explicitly enabled.
        # Set RETURN_ANNOTATED_IMAGE=false in production to avoid proxy timeouts.
        "annotatedImage": annotated_b64 if RETURN_ANNOTATED_IMAGE else None,
        "disclaimer": DISCLAIMER,
    }


