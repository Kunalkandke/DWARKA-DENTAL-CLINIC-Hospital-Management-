"""
Dental X-ray Analysis API  –  FastAPI + YOLO11m
Run:  uvicorn app:app --host 127.0.0.1 --port 8000

Environment variables (all optional – defaults shown):
  MODEL_PATH      Path to YOLO weights, resolved relative to this file.  (default: best.pt)
  IMGSZ           Inference image size matching training.                 (default: 800)
  CONF            Confidence threshold.                                   (default: 0.28)
  MODEL_VERSION   Version tag returned in every prediction response.      (default: yolo11m-dental-v1)
  ML_API_KEY      If set, every request except GET /health must supply
                  the header  x-api-key: <value>, else 401 is returned.
  ALLOWED_ORIGINS Comma-separated list of allowed CORS origins.
                  Example: https://example.com,https://www.example.com
                  Leave empty (default) to allow NO cross-origin requests.
"""

from __future__ import annotations

import base64
import io
import logging
import os
from pathlib import Path
from typing import List

import cv2
import numpy as np
from fastapi import FastAPI, File, Header, HTTPException, Request, UploadFile
from fastapi.concurrency import run_in_threadpool
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
from ultralytics import YOLO

# ---------------------------------------------------------------------------
# Logging
# ---------------------------------------------------------------------------
logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Configuration from environment
# ---------------------------------------------------------------------------
_HERE = Path(__file__).resolve().parent

MODEL_PATH: Path = _HERE / os.environ.get("MODEL_PATH", "app.pt")
IMGSZ: int = int(os.environ.get("IMGSZ", "800"))
CONF: float = float(os.environ.get("CONF", "0.28"))
MODEL_VERSION: str = os.environ.get("MODEL_VERSION", "yolo11m-dental-v1")
ML_API_KEY: str | None = os.environ.get("ML_API_KEY", None) or None  # empty string treated as unset

_raw_origins = os.environ.get("ALLOWED_ORIGINS", "")
ALLOWED_ORIGINS: list[str] = [o.strip() for o in _raw_origins.split(",") if o.strip()]

# Fixed class order as the model was trained
CLASS_NAMES: list[str] = ["Fillings", "Implant", "Cavity", "Impacted Tooth"]

# Suggestion strings keyed by class name
SUGGESTIONS: dict[str, str] = {
    "Cavity": (
        "Possible caries detected. A clinical examination and radiographic confirmation are "
        "recommended. Restoration (filling) evaluation may be required."
    ),
    "Fillings": (
        "Existing restoration observed. Monitor for marginal leakage, secondary decay, or "
        "fracture at recall appointments."
    ),
    "Implant": (
        "Existing dental implant present. Assess bone levels and peri-implant tissue health "
        "at each recall visit."
    ),
    "Impacted Tooth": (
        "Impacted tooth detected. Referral for surgical or orthodontic assessment is advised "
        "to prevent complications."
    ),
}

DISCLAIMER = (
    "This output is generated by an AI model and is intended for decision-support purposes only. "
    "It must be reviewed and confirmed by a qualified dental professional before any clinical action is taken."
)

MAX_FILE_SIZE = 10 * 1024 * 1024  # 10 MB
ALLOWED_CONTENT_TYPES = {"image/jpeg", "image/png"}
ALLOWED_EXTENSIONS = {".jpg", ".jpeg", ".png"}

# Colour-check threshold: if mean(|R-G|, |R-B|, |G-B|) exceeds this the
# image is considered strongly coloured and likely not a grayscale X-ray.
COLOUR_THRESHOLD = 20.0

# If True, the annotatedImage base64 field is included in the response.
# Set RETURN_ANNOTATED_IMAGE=false in production to keep response size small
# and avoid proxy timeouts (the Node backend saves it to disk anyway).
RETURN_ANNOTATED_IMAGE: bool = os.environ.get("RETURN_ANNOTATED_IMAGE", "true").lower() != "false"

# ---------------------------------------------------------------------------
# Model loading (once at startup)
# ---------------------------------------------------------------------------
_model: YOLO | None = None
_model_loaded: bool = False
_model_load_error: str = ""


def _load_model() -> None:
    global _model, _model_loaded, _model_load_error
    try:
        logger.info("Loading YOLO model from %s …", MODEL_PATH)
        _model = YOLO(str(MODEL_PATH))
        # Override names to guarantee fixed class order regardless of what the
        # saved model metadata says.
        # In ultralytics ≥ 8.3 YOLO.names is a read-only property; the mutable
        # dict lives on the inner model object.
        _names_override = {i: name for i, name in enumerate(CLASS_NAMES)}
        try:
            # ultralytics ≥ 8.3: set on the underlying nn model
            _model.model.names = _names_override
        except AttributeError:
            # ultralytics < 8.3 fallback: direct assignment worked
            _model.names = _names_override
        _model_loaded = True
        logger.info("Model loaded successfully. Classes: %s", CLASS_NAMES)
    except Exception as exc:  # noqa: BLE001
        _model_load_error = str(exc)
        logger.error("Failed to load model: %s", exc)


_load_model()

